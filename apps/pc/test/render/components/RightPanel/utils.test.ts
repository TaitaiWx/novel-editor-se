describe('normalizePersonName / escapeRegex / estimateAppearanceHeat', () => {
  it('removes whitespace and lowercases', () => {
    expect(normalizePersonName(' 林 远 ')).toBe('林远');
    expect(normalizePersonName('Lin  Yuan')).toBe('linyuan');
  });

  it('escapes regex metacharacters', () => {
    expect(escapeRegex('a.b*c(d)[e]')).toBe('a\\.b\\*c\\(d\\)\\[e\\]');
    expect(new RegExp(escapeRegex('C++')).test('学 C++')).toBe(true);
  });

  it('counts name occurrences, safely with special chars', () => {
    const text = '林远看向苏晴。苏晴笑了，林远也笑了。林远转身离开。';
    expect(estimateAppearanceHeat(text, '林远')).toBe(3);
    expect(estimateAppearanceHeat(text, ' 苏晴 ')).toBe(2);
    expect(estimateAppearanceHeat(text, '赵无极')).toBe(0);
    expect(estimateAppearanceHeat(text, '   ')).toBe(0);
    expect(estimateAppearanceHeat('a.b ab a.b', 'a.b')).toBe(2);
  });
});

describe('splitTextIntoChunks', () => {
  it('returns [] for empty content', () => {
    expect(splitTextIntoChunks('', 100)).toEqual([]);
    expect(splitTextIntoChunks('  \n\n  ', 100)).toEqual([]);
  });

  it('packs paragraphs into chunks up to maxChars', () => {
    const content = '林远醒来。\n\n苏晴在门外。\n\n\n远处传来钟声。';
    expect(splitTextIntoChunks(content, 100)).toEqual([
      '林远醒来。\n\n苏晴在门外。\n\n远处传来钟声。',
    ]);
    expect(splitTextIntoChunks(content, 13)).toEqual([
      '林远醒来。\n\n苏晴在门外。',
      '远处传来钟声。',
    ]);
  });

  it('hard-splits paragraphs longer than maxChars', () => {
    const long = '剑'.repeat(25);
    const chunks = splitTextIntoChunks(`短段\n\n${long}\n\n尾声`, 10);
    expect(chunks).toEqual(['短段', '剑'.repeat(10), '剑'.repeat(10), '剑'.repeat(5), '尾声']);
  });
});

describe('extractJsonBlock', () => {
  it('extracts ```json fenced blocks', () => {
    expect(extractJsonBlock('好的：\n```json\n{"a":1}\n```\n以上')).toBe('{"a":1}');
  });

  it('extracts generic fenced blocks', () => {
    expect(extractJsonBlock('```\n[1,2]\n```')).toBe('[1,2]');
  });

  it('falls back to outermost braces', () => {
    expect(extractJsonBlock('结果是 {"name":"林远"} 完毕')).toBe('{"name":"林远"}');
  });

  it('returns null when nothing JSON-like exists', () => {
    expect(extractJsonBlock('没有 JSON')).toBeNull();
    expect(extractJsonBlock('} reversed {')).toBeNull();
  });

  it('extracts bare arrays, ignoring brackets inside strings and non-JSON brackets', () => {
    expect(extractJsonBlock('如下：[{"a":1},{"b":2}] 完')).toBe('[{"a":1},{"b":2}]');
    expect(extractJsonBlock('[{"t":"含 ] 与 } 的标题"}]')).toBe('[{"t":"含 ] 与 } 的标题"}]');
    expect(extractJsonBlock('结果[注]：{"name":"林远"}')).toBe('{"name":"林远"}');
    expect(extractJsonBlock('对象优先 {"list":[1,2]} 尾')).toBe('{"list":[1,2]}');
  });
});

