function makeEntry(overrides: Partial<OutlineEntry> = {}): OutlineEntry {
  return {
    cacheKey: '',
    line: 1,
    level: 1,
    text: '第一章 风起青萍',
    summary: '',
    autoGenerated: false,
    wordCount: 0,
    ...overrides,
  };
}

function makeCharacter(overrides: Partial<Character> = {}): Character {
  return {
    id: 1,
    name: '林远',
    role: '主角',
    category: 'major',
    description: '',
    currentState: [],
    ...overrides,
  };
}

function heading(text: string, line: number, level = 1): OutlineNode {
  return { text, line, level, source: 'chinese-section' };
}

function relation(
  sourceId: number,
  targetId: number,
  tone: CharacterRelation['tone']
): CharacterRelation {
  return { id: `${sourceId}-${targetId}-${tone}`, sourceId, targetId, label: '', tone, note: '' };
}

describe('fnv1a32 / cache keys', () => {
  it('matches known FNV-1a test vectors', () => {
    expect(fnv1a32('')).toBe('811c9dc5');
    expect(fnv1a32('a')).toBe('e40c292c');
    expect(fnv1a32('foobar')).toBe('bf9cf968');
  });

  it('always returns 8 lowercase hex chars and is deterministic', () => {
    const value = fnv1a32('第一章 风起青萍');
    expect(value).toMatch(/^[0-9a-f]{8}$/);
    expect(fnv1a32('第一章 风起青萍')).toBe(value);
    expect(fnv1a32('第二章 风起青萍')).not.toBe(value);
  });

  it('buildOutlineEntryCacheKey prefers cacheKey, then originalText, then text', () => {
    expect(buildOutlineEntryCacheKey(makeEntry({ cacheKey: 'abc' }))).toBe('abc');
    expect(buildOutlineEntryCacheKey(makeEntry({ originalText: '第一章', text: 'AI 标题' }))).toBe(
      fnv1a32('第一章')
    );
    expect(buildOutlineEntryCacheKey(makeEntry({ text: '第三章 夜袭' }))).toBe(
      fnv1a32('第三章 夜袭')
    );
  });

  it('buildOutlineCacheKeyFromTitle trims the title', () => {
    expect(buildOutlineCacheKeyFromTitle('  第一章  ')).toBe(fnv1a32('第一章'));
  });

  it('migrateCacheKey returns null for already-hashed keys', () => {
    expect(migrateCacheKey(fnv1a32('第一章'))).toBeNull();
  });

  it('migrateCacheKey hashes legacy raw titles and strips fingerprints', () => {
    expect(migrateCacheKey('第一章 风起')).toBe(fnv1a32('第一章 风起'));
    expect(migrateCacheKey('第一章 风起|fp-123|x')).toBe(fnv1a32('第一章 风起'));
    // uppercase hex is not considered migrated
    expect(migrateCacheKey('ABCDEF12')).toBe(fnv1a32('ABCDEF12'));
  });
});

