describe('buildOutlineEntries / extractChapterContent', () => {
  const content = [
    '第一章', // 1
    '林远在青云山下醒来。', // 2
    '', // 3
    '苏晴递来一碗药。', // 4
    '第二章 试剑大会', // 5
    '剑光如雪。', // 6
  ].join('\n');

  it('returns [] for blank content', () => {
    expect(buildOutlineEntries('   \n ', [])).toEqual([]);
  });

  it('builds one untitled entry when there are no headings', () => {
    const entries = buildOutlineEntries('林远 醒来\n\n苏晴', []);
    expect(entries).toEqual([
      {
        cacheKey: fnv1a32('未命名章节'),
        line: 1,
        level: 1,
        text: '未命名章节',
        originalText: '',
        summary: '林远 醒来 苏晴',
        autoGenerated: false,
        needsAiTitle: true,
        wordCount: 6,
      },
    ]);
  });

  it('builds entries per chapter heading with summary and word count', () => {
    const headings = [heading('第一章', 1), heading('第二章 试剑大会', 5)];
    const entries = buildOutlineEntries(content, headings);
    expect(entries).toHaveLength(2);
    expect(entries[0]).toMatchObject({
      line: 1,
      text: '第一章',
      originalText: '第一章',
      summary: '林远在青云山下醒来。 苏晴递来一碗药。',
      needsAiTitle: true,
      wordCount: 18,
      cacheKey: fnv1a32('第一章'),
    });
    expect(entries[1]).toMatchObject({
      line: 5,
      text: '第二章 试剑大会',
      summary: '剑光如雪。',
      needsAiTitle: false,
      wordCount: 5,
    });
  });

  it('extractChapterContent returns body between headings, truncated', () => {
    const headings = [heading('第一章', 1), heading('第二章 试剑大会', 5)];
    const entries = buildOutlineEntries(content, headings);
    expect(extractChapterContent(content, entries, 0, 1000)).toBe(
      '林远在青云山下醒来。\n\n苏晴递来一碗药。'
    );
    expect(extractChapterContent(content, entries, 1, 1000)).toBe('剑光如雪。');
    expect(extractChapterContent(content, entries, 0, 4)).toBe('林远在青');
    expect(extractChapterContent(content, entries, -1, 10)).toBe('');
    expect(extractChapterContent(content, entries, 2, 10)).toBe('');
  });

  it('handles CRLF content', () => {
    const entries = buildOutlineEntries('第一章 起\r\n正文\r\n', [heading('第一章 起', 1)]);
    expect(entries[0].summary).toBe('正文');
  });
});

