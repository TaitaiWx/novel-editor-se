// ─── IntersectionObserver stub（可手动触发） ─────────────────────────────
type IOCallback = (entries: Array<{ target: Element; isIntersecting: boolean }>) => void;
const observers: Array<{ cb: IOCallback; targets: Element[] }> = [];
class FakeIO {
  private record: { cb: IOCallback; targets: Element[] };
  constructor(cb: IOCallback) {
    this.record = { cb, targets: [] };
    observers.push(this.record);
  }
  observe(el: Element) {
    this.record.targets.push(el);
  }
  disconnect() {
    this.record.targets = [];
  }
}

const entry = (line: number, text: string, extra: Partial<OutlineEntry> = {}): OutlineEntry => ({
  cacheKey: `k-${line}`,
  line,
  level: 1,
  text,
  summary: '',
  autoGenerated: false,
  source: 'document',
  wordCount: 100,
  ...extra,
});

const liveEntries = [
  entry(1, '第一章', { needsAiTitle: true }),
  entry(10, '第二章', { needsAiTitle: true, wordCount: 20000 }),
  entry(20, '第三章'),
];
const dbEntries = [
  entry(1, '序幕', { source: 'database', lineHint: 5, anchorText: '锚点', summary: '库内摘要' }),
  entry(2, '高潮', { source: 'database', lineHint: 0 }),
];

